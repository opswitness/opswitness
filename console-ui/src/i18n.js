export function resolveUiLanguage(value) {
  return value === 'zh' ? 'zh' : DEFAULT_UI_LANGUAGE;
}

export function translateUi(language, source, values = {}) {
  const template = resolveUiLanguage(language) === 'en' ? (english[source] || source) : source;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key) => (
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match
  ));
}

const apiErrorSources = {
  origin_denied: '当前工作台地址未获授权。请从本机地址或已配对的私网 HTTPS 地址重新打开 OpsWitness。',
};

export function translateApiError(language, code, fallback) {
  const source = apiErrorSources[code];
  return source ? translateUi(language, source) : fallback;
}
